// A random UUID (version 4). crypto.randomUUID only exists on secure pages
// (https or localhost), and the app is opened over plain http on a tablet during
// testing. getRandomValues works on any page. The database wants real UUIDs.
export function uid(): string {
  const b = new Uint8Array(16)
  crypto.getRandomValues(b)
  b[6] = (b[6] & 0x0f) | 0x40
  b[8] = (b[8] & 0x3f) | 0x80
  const h = Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("")
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`
}
